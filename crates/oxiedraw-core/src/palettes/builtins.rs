/// Name of the palette the Presets tab starts on.
pub const DEFAULT_PRESET: &str = "Gouache Basics";

fn palette(name: &str, colors: &[Color]) -> Palette {
    Palette {
        name: name.to_string(),
        colors: colors.to_vec(),
        builtin: true,
    }
}

/// The shipped palettes, in the order they appear in the presets list.
pub fn builtin_palettes() -> Vec<Palette> {
    vec![
        palette(DEFAULT_PRESET, &GOUACHE_BASICS),
        palette("Skin Tones", &SKIN_TONES),
        palette("Muted Landscape", &MUTED_LANDSCAPE),
        palette("Pastel", &PASTEL),
        palette("Grayscale 9", &GRAYSCALE_9),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shipped_palettes_are_named_uniquely_and_non_empty() {
        let palettes = builtin_palettes();
        assert_eq!(palettes.len(), 5);
        for palette in &palettes {
            assert!(!palette.colors.is_empty());
            assert!(palette.builtin);
            assert_eq!(
                palettes.iter().filter(|p| p.name == palette.name).count(),
                1,
                "{} appears twice",
                palette.name
            );
        }
    }

    #[test]
    fn the_default_preset_is_one_of_them() {
        assert!(builtin_palettes().iter().any(|p| p.name == DEFAULT_PRESET));
    }
}
